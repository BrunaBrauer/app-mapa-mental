import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';

const compile = async path => ts.transpileModule(await readFile(path, 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const url = code => `data:text/javascript;base64,${Buffer.from(code).toString('base64')}`;
const { updateNodeMapLink, mapLinksForNode } = await import(url(await compile('lib/map-links.ts')));
const [editor, canvas, nodeView, toolbar] = await Promise.all(['components/Editor.tsx', 'components/MapCanvas.tsx', 'components/MindNodeView.tsx', 'components/NodeQuickToolbar.tsx'].map(path => readFile(path, 'utf8')));
assert.match(toolbar, /action\('maps'\)/, 'O menu do nó abre o gerenciamento de vínculos.');
assert.match(nodeView, /data\.onOpenLinkedMaps\?\.\(item\.id\)/, 'O indicador do nó abre o mapa vinculado.');
assert.match(canvas, /onOpenLinkedMaps, onPatch/, 'O canvas encaminha o clique do indicador.');
assert.match(editor, /mapTrail\.length > 0 && <button/, 'A navegação oferece retorno ao mapa de origem.');
const migrationUrl = url('export const migrateMapLayouts = map => map;');
const serverCode = (await compile('lib/server-maps.ts')).replace("'./layout-migration'", JSON.stringify(migrationUrl));
const { validMap } = await import(url(serverCode));
const sourceId = '11111111-1111-4111-8111-111111111111';
const targetId = '22222222-2222-4222-8222-222222222222';
const secondId = '33333333-3333-4333-8333-333333333333';
const source = { id: sourceId, title: 'Principal', layout: 'horizontal', updatedAt: Date.now(), nodes: [{ id: 'root', parentId: null, text: 'Tópico', x: 0, y: 0 }] };
const target = { id: targetId, title: 'Detalhes', layout: 'network', updatedAt: Date.now(), nodes: [{ id: 'detail', parentId: null, text: 'Conteúdo independente', x: 30, y: 40 }] };
const linked = updateNodeMapLink(source, 'root', targetId, true);
assert.deepEqual(linked.nodes[0].linkedMapIds, [targetId]);
assert.equal(validMap(linked), true, 'O mapa com vínculo precisa passar pela validação da API.');
assert.equal(updateNodeMapLink(linked, 'root', targetId, true), linked, 'Um vínculo não deve ser duplicado.');
const multiple = updateNodeMapLink(linked, 'root', secondId, true);
assert.deepEqual(multiple.nodes[0].linkedMapIds, [targetId, secondId]);
assert.equal(updateNodeMapLink(multiple, 'root', sourceId, true), multiple, 'O mapa não pode se vincular a si mesmo.');
assert.equal(mapLinksForNode(multiple, 'root', [{ ...target, title: 'Novo nome' }])[0].map.title, 'Novo nome', 'Renomear o destino não altera a associação.');
assert.equal(mapLinksForNode(multiple, 'root', [target])[1].map, undefined, 'Mapas excluídos aparecem como indisponíveis.');
const unlinked = updateNodeMapLink(multiple, 'root', targetId, false);
assert.deepEqual(unlinked.nodes[0].linkedMapIds, [secondId]);
assert.deepEqual(target.nodes, [{ id: 'detail', parentId: null, text: 'Conteúdo independente', x: 30, y: 40 }], 'Vincular e desvincular não modifica o destino.');
assert.equal(validMap({ ...multiple, nodes: [{ ...multiple.nodes[0], linkedMapIds: [targetId, targetId] }] }), false, 'A API rejeita vínculos duplicados.');
assert.equal(validMap({ ...multiple, nodes: [{ ...multiple.nodes[0], linkedMapIds: ['invalido'] }] }), false, 'A API rejeita IDs inválidos.');
assert.equal(validMap({ ...multiple, nodes: [{ ...multiple.nodes[0], linkedMapIds: [sourceId] }] }), false, 'A API rejeita vínculos do mapa para si mesmo.');
console.log('Vínculos entre mapas: IDs estáveis, múltiplos destinos, independência, remoção e validação OK.');
